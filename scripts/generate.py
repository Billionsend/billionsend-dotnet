def class_name(group: list[str]) -> str:
    return "".join(pascal(g) for g in group) + "Resource"


def options_type(op: Operation) -> str:
    if op.stream:
        return "EventStreamOptions"
    if op.idempotent and op.batch_validation:
        return "BatchSendOptions"
    if op.idempotent:
        return "IdempotentRequestOptions"
    if op.batch_validation:
        return "BatchRequestOptions"
    return "RequestOptions"


def query_doc(op: Operation) -> str:
    parts = []
    for q in op.query_params:
        text = code(q.name)
        if q.enum:
            text += " (" + ", ".join(code(v) for v in q.enum) + ")"
        if q.array:
            text += " (a list, sent comma-separated)"
        if q.required:
            text += " (required)"
        parts.append(text)
    return (
        "Query parameters"
        + ("" if op.query_required else ", or <see langword=\"null\"/>")
        + ": "
        + ", ".join(parts)
        + "."
        if parts
        else ""
    )


def signature(op: Operation, *, paginator: bool = False) -> list[str]:
    args = [f"string {p.cs}" for p in op.path_params]
    if op.body and not paginator:
        if op.multipart:
            args.append(
                "IReadOnlyDictionary<string, object?> body"
                if op.body_required
                else "IReadOnlyDictionary<string, object?>? body = null"
            )
        else:
            args.append("object body" if op.body_required else "object? body = null")
    if op.query_params:
        args.append(
            "IReadOnlyDictionary<string, object?> query"
            if op.query_required
            else "IReadOnlyDictionary<string, object?>? query = null"
        )
    args.append(f"{options_type(op)}? options = null")
    args.append("CancellationToken cancellationToken = default")
    return args


def method_docs(op: Operation, indent: str) -> list[str]:
    lines = [f"{indent}/// <summary>"]
    lines += doc_lines(xml(sentence(op.summary or op.operation_id)), indent)
    lines.append(f"{indent}/// </summary>")
    remarks: list[str] = []
    if op.description:
        remarks += [xml(p) for p in op.description.split("\n\n")]
    if op.idempotent:
        remarks.append(
            "Always sent with an <c>Idempotency-Key</c>: <c>options.IdempotencyKey</c> when "
            "given, otherwise a new one for this call, so that its retries never send twice."
        )
    if not op.auth:
        remarks.append("Takes no API key: none is sent, even when the client has one.")
    if op.path in STREAM_ENDS_ON:
        remarks.append(
            "The stream ends (the loop finishes) after "
            + " or ".join(code(e) for e in STREAM_ENDS_ON[op.path])
            + "."
        )
    remarks.append(f"<c>{op.method} {xml(op.path)}</c> (<c>{op.operation_id}</c>)")
    lines.append(f"{indent}/// <remarks>")
    for paragraph in remarks:
        lines.append(f"{indent}/// <para>")
        lines += doc_lines(paragraph, indent)
        lines.append(f"{indent}/// </para>")
    lines.append(f"{indent}/// </remarks>")
    for p in op.path_params:
        text = code(p.name) + (": " + xml(p.description) if p.description else ".")
        lines += doc_lines(f'<param name="{p.cs.lstrip("@")}">{text}</param>', indent)
    if op.body:
        schema = f" ({code(op.body_schema)})" if op.body_schema else ""
        optional = "" if op.body_required else ", or <see langword=\"null\"/> to send none"
        if op.multipart:
            lines += doc_lines(
                f'<param name="body">The form fields{schema} by name: a '
                f'<see cref="FileUpload"/> becomes a file part, a string is sent as it is and '
                f"anything else (an object or a list) as its JSON text{optional}.</param>",
                indent,
            )
        else:
            lines += doc_lines(
                f'<param name="body">The request body{schema}: any object that serializes to it '
                f"(a <see cref=\"JsonNode\"/>, a dictionary, an anonymous object or your own "
                f"type){optional}.</param>",
                indent,
            )
    if op.query_params:
        lines += doc_lines(f'<param name="query">{query_doc(op)}</param>', indent)
    lines += doc_lines(
        '<param name="options">Per-call options, or <see langword="null"/>.</param>', indent
    )
    lines += doc_lines(
        '<param name="cancellationToken">Cancels the call and its retries.</param>', indent
    )
    if op.stream:
        lines += doc_lines(
            "<returns>The open stream: iterate it with <c>await foreach</c>.</returns>", indent
        )
    else:
        schema = f" ({code(op.response_schema)})" if op.response_schema else ""
        lines += doc_lines(f"<returns>The parsed JSON answer{schema}.</returns>", indent)
    lines += doc_lines(
        '<exception cref="BillionSendException">The API refused the request, or it got no '
        "answer; the subclass tells which.</exception>",
        indent,
    )
    return lines


def call_lines(op: Operation, indent: str) -> list[str]:
    """The ``new ApiCall(...) { ... }`` argument, one line per part."""
    path = (
        "new[] { " + ", ".join(p.cs for p in op.path_params) + " }"
        if op.path_params
        else "ApiCall.NoPath"
    )
    init: list[str] = []
    if op.body:
        init.append("Body = body")
        if op.multipart:
            init.append("Multipart = true")
    if op.query_params:
        init.append("Query = query")
    if op.idempotent:
        init.append("Idempotent = true")
    if not op.auth:
        init.append("Auth = false")
    if op.batch_validation:
        init.append("BatchValidation = options?.BatchValidation")
    head = [f'{indent}new ApiCall("{op.method}", "{op.path}", {path})']
    if len(head[0]) + 1 > WIDTH:
        head = [
            f"{indent}new ApiCall(",
            f'{indent}    "{op.method}",',
            f'{indent}    "{op.path}",',
            f"{indent}    {path})",
        ]
    if not init:
        return [*head[:-1], head[-1] + ","]
    return [*head, f"{indent}{{", *[f"{indent}    {i}," for i in init], f"{indent}}},"]


def render_method(op: Operation, indent: str) -> list[str]:
    lines = method_docs(op, indent)
    args = signature(op)
    inner = indent + "        "
    if op.stream:
        ends = STREAM_ENDS_ON.get(op.path)
        ends_expr = (
            "new[] { " + ", ".join(f'"{e}"' for e in ends) + " }"
            if ends
            else "System.Array.Empty<string>()"
        )
        lines.append(f"{indent}public Task<EventStream> {op.name}Async(")
        call = f"{indent}    _api.OpenEventStreamAsync("
        tail = [f"{inner}{ends_expr},", f"{inner}options,", f"{inner}cancellationToken);"]
    else:
        lines.append(f"{indent}public Task<JsonNode?> {op.name}Async(")
        call = f"{indent}    _api.RequestAsync("
        tail = [f"{inner}options,", f"{inner}cancellationToken);"]
    lines += [f"{indent}    {a}," for a in args[:-1]]
    lines.append(f"{indent}    {args[-1]}) =>")
    lines.append(call)
    lines += call_lines(op, inner)
    lines += tail
    return lines


def render_paginator(op: Operation, indent: str) -> list[str]:
    args = signature(op, paginator=True)
    path_args = [p.cs for p in op.path_params]
    lines = [f"{indent}/// <summary>"]
    lines += doc_lines(
        f"Every item of <see cref=\"{op.name}Async\"/>, fetching pages as the loop needs them.",
        indent,
    )
    lines.append(f"{indent}/// </summary>")
    lines.append(f"{indent}/// <remarks>")
    lines += doc_lines(
        "Walks forward from <c>after</c> (or the first page) with the last id of each page; "
        "started with <c>before</c>, it walks backward with the first id. A failed page is "
        "thrown as its <see cref=\"BillionSendException\"/>.",
        indent,
    )
    lines.append(f"{indent}/// </remarks>")
    for p in op.path_params:
        lines += doc_lines(f'<param name="{p.cs.lstrip("@")}">{code(p.name)}.</param>', indent)
    lines += doc_lines(f'<param name="query">{query_doc(op)}</param>', indent)
    lines += doc_lines(
        '<param name="options">Options for each page request, or <see langword="null"/>.'
        "</param>",
        indent,
    )
    lines += doc_lines(
        '<param name="cancellationToken">Stops the iteration.</param>', indent
    )
    lines += doc_lines("<returns>The list's items, one at a time.</returns>", indent)
    lines.append(f"{indent}public IAsyncEnumerable<JsonNode> {op.name}AllAsync(")
    lines += [f"{indent}    {a}," for a in args[:-1]]
    lines.append(f"{indent}    {args[-1]}) =>")
    fetch_args = ", ".join([*path_args, "page", "options", "ct"])
    lines.append(f"{indent}    Pagination.IterateAsync(")
    lines.append(f"{indent}        (page, ct) => {op.name}Async({fetch_args}),")
    lines.append(f"{indent}        query,")
    lines.append(f"{indent}        cancellationToken);")
    return lines


def render(ops: list[Operation]) -> str:
    groups: dict[tuple[str, ...], list[Operation]] = {}
    for op in ops:
        groups.setdefault(tuple(op.group), []).append(op)
    for group in list(groups):
        for i in range(1, len(group)):
            groups.setdefault(group[:i], [])
    roots = sorted(g for g in groups if len(g) == 1)

    lines = [
        HEADER,
        "#nullable enable",
        "",
        "using System.Collections.Generic;",
        "using System.Text.Json.Nodes;",
        "using System.Threading;",
        "using System.Threading.Tasks;",
        "using BillionSend.Internal;",
        "using BillionSend.Resources;",
        "",
        "namespace BillionSend",
        "{",
        "    public partial class BillionSendClient",
        "    {",
    ]
    for root in roots:
        lines.append(f"        /// <summary>The <c>{root[0]}</c> operations.</summary>")
        lines.append(
            f"        public {class_name(list(root))} {pascal(root[0])} {{ get; private set; }} = null!;"
        )
        lines.append("")
    lines.append("        private partial void InitResources(ApiClient api)")
    lines.append("        {")
    for root in roots:
        lines.append(f"            {pascal(root[0])} = new {class_name(list(root))}(api);")
    lines.append("        }")
    lines.append("    }")
    lines.append("}")
    lines.append("")
    lines.append("namespace BillionSend.Resources")
    lines.append("{")

    first = True
    for group in sorted(groups):
        cls = class_name(list(group))
        children = sorted(g for g in groups if len(g) == len(group) + 1 and g[:-1] == group)
        if not first:
            lines.append("")
        first = False
        lines.append(f"    /// <summary>The <c>{'.'.join(group)}</c> operations.</summary>")
        lines.append(f"    public sealed class {cls}")
        lines.append("    {")
        lines.append("        private readonly ApiClient _api;")
        lines.append("")
        lines.append(f"        internal {cls}(ApiClient api)")
        lines.append("        {")
        lines.append("            _api = api;")
        for child in children:
            lines.append(f"            {pascal(child[-1])} = new {class_name(list(child))}(api);")
        lines.append("        }")
        for child in children:
            lines.append("")
            lines.append(
                f"        /// <summary>The <c>{'.'.join(child)}</c> operations.</summary>"
            )
            lines.append(f"        public {class_name(list(child))} {pascal(child[-1])} {{ get; }}")
        for op in sorted(groups[group], key=lambda o: o.name):
            lines.append("")
            lines += render_method(op, "        ")
            if op.paginated:
                lines.append("")
                lines += render_paginator(op, "        ")
        lines.append("    }")
    lines.append("}")
    return "\n".join(lines) + "\n"


def generate() -> str:
    spec = Spec(json.loads(SNAPSHOT.read_text(encoding="utf-8")))
    return render(spec.operations())


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Generate the SDK's resource classes.")
    parser.add_argument(
        "--check", action="store_true", help="fail if the generated file is stale"
    )
    args = parser.parse_args(argv)
    text = generate()
    relative = OUTPUT.relative_to(ROOT)
    if args.check:
        current = OUTPUT.read_text(encoding="utf-8") if OUTPUT.exists() else None
        if current != text:
            print(f"{relative} is stale: run `python3 scripts/generate.py`", file=sys.stderr)
            return 1
        print(f"{relative} matches the snapshot")
        return 0
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_text(text, encoding="utf-8")
    print(f"wrote {relative}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
