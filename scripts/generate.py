"""Generate the SDK's resource classes from the OpenAPI snapshot.

Writes ``src/BillionSend/Generated/Resources.g.cs`` from
``openapi/api.openapi.json``: one class per resource group, one async method
per operation, and the client's top-level resource properties.

Each operation's method is named by its ``operationId``: the dotted path of the
method, segments in camelCase (``emails.receiving.attachments.list``), written
here in PascalCase with the ``Async`` suffix
(``client.Emails.Receiving.Attachments.ListAsync``). One operation is also the
group of others: ``emails.metrics`` is ``client.Emails.Metrics.GetAsync``,
beside ``emails.metrics.links`` / ``countries`` / ``clients``. Every cursor-paginated
list also gets an ``...AllAsync`` iterator (``ListAllAsync``,
``SearchAllAsync``).

Only the standard library is used, so CI needs nothing but Python 3.

Usage::

    python3 scripts/generate.py          # rewrite the generated file
    python3 scripts/generate.py --check  # fail if it differs from the snapshot
"""

from __future__ import annotations

import argparse
import json
import re
import sys
import textwrap
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parent.parent
SNAPSHOT = ROOT / "openapi" / "api.openapi.json"
OUTPUT = ROOT / "src" / "BillionSend" / "Generated" / "Resources.g.cs"

HTTP_METHODS = ("get", "put", "post", "patch", "delete")
IDEMPOTENCY_KEY_HEADER = "idempotency-key"
BATCH_VALIDATION_HEADER = "x-batch-validation"
WIDTH = 100

# One inbox's stream is over after that inbox's deletion or expiry.
STREAM_ENDS_ON = {"/inboxes/{inbox_id}/events": ["inbox.deleted", "inbox.expired"]}
# Sent as the Last-Event-ID header by the event stream instead.
STREAM_SKIPPED_QUERY = {"last_event_id"}

CSHARP_KEYWORDS = {
    "abstract", "as", "base", "bool", "break", "byte", "case", "catch", "char", "checked",
    "class", "const", "continue", "decimal", "default", "delegate", "do", "double", "else",
    "enum", "event", "explicit", "extern", "false", "finally", "fixed", "float", "for",
    "foreach", "goto", "if", "implicit", "in", "int", "interface", "internal", "is", "lock",
    "long", "namespace", "new", "null", "object", "operator", "out", "override", "params",
    "private", "protected", "public", "readonly", "ref", "return", "sbyte", "sealed", "short",
    "sizeof", "stackalloc", "static", "string", "struct", "switch", "this", "throw", "true",
    "try", "typeof", "uint", "ulong", "unchecked", "unsafe", "ushort", "using", "virtual",
    "void", "volatile", "while",
}
RESERVED_PARAMS = {"body", "query", "options", "cancellationToken"}

HEADER = (
    "// <auto-generated>\n"
    "// Generated by scripts/generate.py from openapi/api.openapi.json. Do not edit by hand:\n"
    "// change the snapshot (scripts/sync_openapi.py) and run the generator again.\n"
    "// </auto-generated>\n"
)


def pascal(text: str) -> str:
    parts = re.split(r"[^0-9a-zA-Z]+", text)
    return "".join(p[:1].upper() + p[1:] for p in parts if p)


def camel(text: str) -> str:
    name = pascal(text)
    name = name[:1].lower() + name[1:]
    if name in CSHARP_KEYWORDS:
        return "@" + name
    if name in RESERVED_PARAMS:
        return name + "Value"
    return name


def xml(text: str) -> str:
    return text.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")


def code(text: str) -> str:
    return f"<c>{xml(text)}</c>"


def doc_lines(text: str, indent: str) -> list[str]:
    """Wrap already-escaped XML doc text into ``///`` lines."""
    out: list[str] = []
    prefix = f"{indent}/// "
    for paragraph in text.split("\n"):
        if paragraph == "":
            continue
        wrapped = textwrap.wrap(
            paragraph,
            width=WIDTH - len(prefix),
            break_long_words=False,
            break_on_hyphens=False,
        )
        out += [prefix + line for line in wrapped]
    return out


def sentence(text: str) -> str:
    text = text.strip()
    return text if text.endswith((".", "!", "?", ":")) else text + "."


@dataclass
class Param:
    name: str  # wire name
    cs: str  # C# parameter name
    description: str
    enum: list[str] | None = None
    array: bool = False
    required: bool = False


@dataclass
class Operation:
    operation_id: str
    method: str
    path: str
    group: list[str]
    name: str
    summary: str
    description: str
    path_params: list[Param] = field(default_factory=list)
    query_params: list[Param] = field(default_factory=list)
    query_required: bool = False
    body: bool = False
    body_required: bool = False
    body_schema: str | None = None
    multipart: bool = False
    response_schema: str | None = None
    idempotent: bool = False
    batch_validation: bool = False
    auth: bool = True
    stream: bool = False
    paginated: bool = False


class Spec:
    def __init__(self, document: dict[str, Any]) -> None:
        self.document = document
        self.schemas: dict[str, Any] = document["components"]["schemas"]

    def resolve(self, schema: dict[str, Any]) -> dict[str, Any]:
        while "$ref" in schema:
            schema = self.schemas[schema["$ref"].rsplit("/", 1)[1]]
        return schema

    @staticmethod
    def ref_name(schema: dict[str, Any] | None) -> str | None:
        if schema and "$ref" in schema:
            return str(schema["$ref"].rsplit("/", 1)[1])
        return None

    def has_id(self, schema: dict[str, Any]) -> bool:
        """Whether every shape an item can take has an ``id`` (the cursor of the next page)."""
        schema = self.resolve(schema)
        branches = schema.get("anyOf") or schema.get("oneOf")
        if branches:
            return all(self.has_id(b) for b in branches)
        return "id" in schema.get("properties", {})

    def operations(self) -> list[Operation]:
        ops: list[Operation] = []
        seen: set[str] = set()
        for path, item in self.document["paths"].items():
            for method, op in item.items():
                if method not in HTTP_METHODS:
                    continue
                operation_id = op.get("operationId")
                if not operation_id or operation_id in seen:
                    raise SystemExit(f"{method.upper()} {path}: missing or repeated operationId")
                seen.add(operation_id)
                ops.append(self.operation(method.upper(), path, op))
        # An operation that is also the group of others (emails.metrics beside
        # emails.metrics.links) becomes that group's GetAsync.
        groups = {tuple(op.group[:i]) for op in ops for i in range(1, len(op.group) + 1)}
        for op in ops:
            full = (*op.group, op.operation_id.split(".")[-1])
            if full in groups:
                if any(o.group == list(full) and o.name == "Get" for o in ops):
                    raise SystemExit(f"{op.operation_id}: its group already has a get")
                op.group = list(full)
                op.name = "Get"
        return ops

    def operation(self, method: str, path: str, op: dict[str, Any]) -> Operation:
        *group, last = op["operationId"].split(".")
        o = Operation(
            operation_id=op["operationId"],
            method=method,
            path=path,
            group=group,
            name=pascal(last),
            summary=op.get("summary", ""),
            description=op.get("description", ""),
            auth=op.get("security", self.document.get("security")) != [],
        )
        for p in op.get("parameters", []):
            where, name = p["in"], p["name"]
            schema = p.get("schema", {})
            if where == "header":
                if name.lower() == IDEMPOTENCY_KEY_HEADER:
                    o.idempotent = True
                elif name.lower() == BATCH_VALIDATION_HEADER:
                    o.batch_validation = True
                else:
                    raise SystemExit(f"{method} {path}: unhandled header parameter {name}")
                continue
            types = schema.get("type")
            types = types if isinstance(types, list) else [types]
            enum = schema.get("enum") or self.resolve(schema.get("items", {})).get("enum")
            param = Param(
                name=name,
                cs=camel(name),
                description=p.get("description") or schema.get("description") or "",
                enum=[str(v) for v in enum if v is not None] if enum else None,
                array="array" in types,
            )
            if where == "path":
                o.path_params.append(param)
            elif where == "query":
                param.required = bool(p.get("required"))
                o.query_required = o.query_required or param.required
                o.query_params.append(param)
            else:
                raise SystemExit(f"{method} {path}: unhandled parameter location {where}")
        order = re.findall(r"{(\w+)}", path)
        o.path_params.sort(key=lambda prm: order.index(prm.name))
        if [prm.name for prm in o.path_params] != order:
            raise SystemExit(f"{method} {path}: path parameters do not match the template")

        body = op.get("requestBody")
        if body:
            content = body.get("content", {})
            if list(content) not in (["application/json"], ["multipart/form-data"]):
                raise SystemExit(f"{method} {path}: unhandled request body {list(content)}")
            o.body = True
            o.multipart = "multipart/form-data" in content
            o.body_required = bool(body.get("required"))
            o.body_schema = self.ref_name(next(iter(content.values())).get("schema"))

        success = [(c, r) for c, r in sorted(op["responses"].items()) if c.startswith("2")]
        if any("text/event-stream" in r.get("content", {}) for _, r in success):
            o.stream = True
            o.query_params = [q for q in o.query_params if q.name not in STREAM_SKIPPED_QUERY]
        else:
            schemas = [
                r["content"]["application/json"].get("schema")
                for _, r in success
                if "application/json" in r.get("content", {})
            ]
            names = [self.ref_name(s) for s in schemas]
            if len(names) == 1:
                o.response_schema = names[0]
            query = {q.name for q in o.query_params}
            if {"after", "before"} <= query and len(schemas) == 1 and schemas[0]:
                page = self.resolve(schemas[0])
                props = page.get("properties", {})
                items = props.get("data", {}).get("items", {})
                o.paginated = "has_more" in props and self.has_id(items)
        return o


